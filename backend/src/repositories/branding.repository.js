const fs = require("fs");
const path = require("path");

// Single-object store (not the array-based JsonStore) — there's only ever
// one branding config in this single-tenant app.
const filePath = path.join(__dirname, "..", "..", "data", "branding.json");

const DEFAULTS = {
  companyName: "AI QA Engineer",
  primaryColor: "#4f46e5",
  footerText: "Generated by AI Website QA Engineer",
  logoUrl: null,
  updatedAt: null,
};

function ensureFile() {
  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  if (!fs.existsSync(filePath)) {
    fs.writeFileSync(filePath, JSON.stringify(DEFAULTS, null, 2));
  }
}

module.exports = {
  get() {
    ensureFile();
    try {
      return { ...DEFAULTS, ...JSON.parse(fs.readFileSync(filePath, "utf-8")) };
    } catch {
      return { ...DEFAULTS };
    }
  },

  update(patch) {
    ensureFile();
    const current = this.get();
    const next = { ...current, ...patch, updatedAt: new Date().toISOString() };
    fs.writeFileSync(filePath, JSON.stringify(next, null, 2));
    return next;
  },
};
